export const dictionary: Readonly<Record<Language, Readonly<Record<TranslationKey, string>>>> = { en, ar };
export const dictionaries = dictionary;

export function resolveLanguage(value: unknown): Language {
  if (typeof value !== 'string') return 'en';
  const locale = value.trim().toLowerCase().replace(/_/g, '-');
  return /^ar(?:-[a-z0-9]{1,8})*$/.test(locale) ? 'ar' : 'en';
}

export function getDirection(language: Language): 'rtl' | 'ltr' {
  return resolveLanguage(language) === 'ar' ? 'rtl' : 'ltr';
}

/** Unknown keys remain visible for diagnostics instead of silently becoming empty text. */
export function t(language: Language, key: string): string {
  const messages = dictionary[resolveLanguage(language)];
  return Object.prototype.hasOwnProperty.call(messages, key) ? messages[key as TranslationKey] : key;
}
