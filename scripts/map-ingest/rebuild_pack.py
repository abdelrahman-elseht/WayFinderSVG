"""Run the immutable pack script with the available native Cairo binding.

PyCairo's Windows wheel bundles Cairo. CairoSVG uses the same surface API for
this vector-only pack; injecting that binding avoids a machine-wide GTK install.
The source pack script and every generated byte are checked against its manifest.
"""
from pathlib import Path
import runpy
import sys
import json
import struct
import zlib

if sys.platform == 'win32':
    try:
        import cairocffi
    except OSError:
        import cairo
        sys.modules['cairocffi'] = cairo

root = Path(__file__).resolve().parents[2]
if len(sys.argv) not in (2, 3) or sys.argv[1] != 'B03_First_Floor/scripts/rebuild.py':
    raise SystemExit('Expected the registered First Floor rebuild script')
namespace = runpy.run_path(str(root / sys.argv[1]), run_name='source_pack')
main = namespace['main']
if len(sys.argv) == 3:
    # Verification rebuilds a disposable copy, never the accepted evidence.
    destination = Path(sys.argv[2]).resolve()
    main.__globals__.update(ROOT=destination, SOURCE=destination/'source', IMAGES=destination/'inspection')

def json_file(path, data):
    if path.name == 'validation.json':
        data = {**data, 'sourceFiles': {key: value.replace('\\', '/') for key, value in data['sourceFiles'].items()}}
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', encoding='utf8', newline='\n') as file:
        json.dump(data, file, ensure_ascii=False, indent=2)
        file.write('\n')

main.__globals__['json_file'] = json_file
original_readme = main.__globals__['create_readme']

def create_readme(*args):
    original_readme(*args)
    path = main.__globals__['ROOT'] / 'README.md'
    path.write_bytes(path.read_bytes().replace(b'\r\n', b'\n'))

main.__globals__['create_readme'] = create_readme
main()

# Pillow's platform encoder uses a different zlib memory level on Windows.
# Recompress regenerated scanlines with the accepted pack's PNG parameters.
# This reads no accepted image and changes neither filters nor pixels.
path = main.__globals__['IMAGES'] / 'seam-detail.png'
png = path.read_bytes()
offset, chunks, compressed = 8, [], b''
while offset < len(png):
    length = struct.unpack('>I', png[offset:offset+4])[0]
    kind = png[offset+4:offset+8]
    value = png[offset+8:offset+8+length]
    offset += length+12
    if kind == b'IDAT':
        compressed += value
    else:
        chunks.append((kind, value))
encoder = zlib.compressobj(6, zlib.DEFLATED, 15, 9, zlib.Z_FILTERED)
encoded = encoder.compress(zlib.decompress(compressed)) + encoder.flush()
def chunk(kind, value):
    return struct.pack('>I', len(value))+kind+value+struct.pack('>I', zlib.crc32(kind+value))
path.write_bytes(png[:8]+b''.join(chunk(k,v) for k,v in chunks if k != b'IEND')+
    b''.join(chunk(b'IDAT', encoded[i:i+65536]) for i in range(0,len(encoded),65536))+chunk(b'IEND', b''))
manifest_path = main.__globals__['ROOT'] / 'manifest.json'
manifest = json.loads(manifest_path.read_text(encoding='utf8'))
manifest['files']['inspection/seam-detail.png'] = main.__globals__['digest'](path)
json_file(manifest_path, manifest)
